const { withProjectBuildGradle } = require('@expo/config-plugins');

const marker = '// @generated by with-android-work-manager-resolution';
const workManagerResolution = `

${marker}
allprojects {
  configurations.configureEach {
    resolutionStrategy {
      force 'androidx.work:work-runtime:2.8.1'
      force 'androidx.work:work-runtime-ktx:2.8.1'
    }
  }
}
`;

module.exports = function withAndroidWorkManagerResolution(config) {
  return withProjectBuildGradle(config, (projectConfig) => {
    if (
      projectConfig.modResults.language === 'groovy'
      && !projectConfig.modResults.contents.includes(marker)
    ) {
      projectConfig.modResults.contents += workManagerResolution;
    }
    return projectConfig;
  });
};
